#!/usr/bin/env python3
"""Regenerate firmware/main/icons.h from shared/icons.json (run after editing the icon list)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
icons = json.loads((root / "shared/icons.json").read_text())
rows = "\n".join(f'    {{"{n}", 0x{cp:04X}}},' for n, cp in sorted(icons.items()))
(root / "firmware/main/icons.h").write_text(f"""// Generated by tools/gen-icons.py from shared/icons.json. Do not edit.
#pragma once
#include <stdint.h>

typedef struct {{
    const char *name;
    uint16_t cp;
}} icon_t;

// Sorted by name for bsearch.
static const icon_t ICONS[] = {{
{rows}
}};
#define ICON_COUNT (sizeof(ICONS) / sizeof(ICONS[0]))
""")
print(len(icons), "icons")
